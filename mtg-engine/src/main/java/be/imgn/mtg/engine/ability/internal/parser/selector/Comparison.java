package be.imgn.mtg.engine.ability.internal.parser.selector;

/// Comparison operators for numeric values in oracle text.
public enum Comparison {
    /// Equal to.
    EQUAL,
    /// Less than.
    LESS,
    /// Less than or equal to.
    LESS_OR_EQUAL,
    /// Greater than.
    GREATER,
    /// Greater than or equal to.
    GREATER_OR_EQUAL
}
