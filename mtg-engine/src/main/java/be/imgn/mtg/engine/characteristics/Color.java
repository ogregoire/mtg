/// The five colors of mana in Magic ({@mtg.rule 105}).
///
/// The colors are white, blue, black, red, and green. Objects can be one or more of these colors,
/// or colorless. Colorless is not a color.
public enum Color {
    WHITE,
    BLUE,
    BLACK,
    RED,
    GREEN
}
